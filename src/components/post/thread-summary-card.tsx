"use client";

import * as React from "react";
import { Sparkles, RefreshCw, ChevronDown, ChevronUp, AlertCircle, Bot } from "lucide-react";
import { Card, CardContent } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { toast } from "sonner";
import type { SummaryResponse } from "@/app/api/ai/summarize/route";

interface ThreadSummaryCardProps {
  postId: string;
  commentCount: number;
}

export function ThreadSummaryCard({ postId, commentCount }: ThreadSummaryCardProps) {
  const [data, setData] = React.useState<SummaryResponse | null>(null);
  const [isLoading, setIsLoading] = React.useState(false);
  const [isExpanded, setIsExpanded] = React.useState(true);
  const [hasLoaded, setHasLoaded] = React.useState(false);

  // Requirement 4 & 5: Visible only when post has 8 or more comments
  if (commentCount < 8) {
    return null;
  }

  const fetchSummary = async (forceRefresh = false) => {
    setIsLoading(true);
    try {
      const res = await fetch("/api/ai/summarize", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ post_id: postId, force_refresh: forceRefresh }),
      });

      if (res.status === 429) {
        const errorJson = await res.json().catch(() => ({}));
        toast.error(
          errorJson.error || "Rate limit exceeded. Maximum AI requests per hour reached."
        );
        return;
      }

      if (!res.ok) {
        const errorJson = await res.json().catch(() => ({}));
        throw new Error(errorJson.error || "Failed to generate AI summary");
      }

      const json: SummaryResponse = await res.json();
      setData(json);
      setHasLoaded(true);
      setIsExpanded(true);
      if (forceRefresh) {
        toast.success("Summary regenerated");
      }
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "AI summarization failed");
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <Card className="curia-card border-accent/40 bg-surface/90 shadow-glow-sm overflow-hidden mb-6 transition-all duration-200">
      <CardContent className="p-4 space-y-3">
        {/* Header Bar */}
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2">
            <div className="flex h-7 w-7 items-center justify-center rounded-lg bg-accent/20 border border-accent/40 text-accent">
              <Sparkles className="h-4 w-4 animate-pulse" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <span className="font-sans font-bold text-sm text-foreground">
                  Thread TL;DR
                </span>
                <Badge
                  variant="outline"
                  className="bg-accent/10 text-accent border-accent/30 text-[10px] font-mono gap-1 py-0 px-1.5"
                >
                  <Bot className="h-3 w-3" />
                  Generated by AI
                </Badge>
                {data?.cached && (
                  <Badge
                    variant="outline"
                    className="bg-surface-raised text-muted-foreground border-border text-[9px] font-mono py-0 px-1.5"
                  >
                    Cached
                  </Badge>
                )}
              </div>
            </div>
          </div>

          <div className="flex items-center gap-1.5">
            {!hasLoaded ? (
              <Button
                size="sm"
                onClick={() => fetchSummary(false)}
                disabled={isLoading}
                className="bg-accent hover:bg-accent/90 text-white font-medium text-xs h-7 px-3 shadow-glow-sm gap-1.5"
              >
                <Sparkles className="h-3.5 w-3.5" />
                <span>TL;DR with AI</span>
              </Button>
            ) : (
              <>
                <Button
                  variant="ghost"
                  size="sm"
                  onClick={() => fetchSummary(true)}
                  disabled={isLoading}
                  className="h-7 text-xs text-muted-foreground hover:text-foreground gap-1 px-2 font-mono"
                  title="Regenerate summary"
                >
                  <RefreshCw className={`h-3 w-3 ${isLoading ? "animate-spin" : ""}`} />
                  <span>Regenerate</span>
                </Button>
                <Button
                  variant="ghost"
                  size="sm"
                  onClick={() => setIsExpanded(!isExpanded)}
                  className="h-7 w-7 p-0 text-muted-foreground hover:text-foreground"
                >
                  {isExpanded ? <ChevronUp className="h-4 w-4" /> : <ChevronDown className="h-4 w-4" />}
                </Button>
              </>
            )}
          </div>
        </div>

        {/* Loading Shimmer State */}
        {isLoading && (
          <div className="space-y-2.5 pt-2 animate-pulse">
            <div className="h-3.5 bg-accent/15 rounded w-4/5" />
            <div className="h-3.5 bg-accent/10 rounded w-full" />
            <div className="h-3.5 bg-accent/10 rounded w-2/3" />
            <div className="pt-2 space-y-1.5">
              <div className="h-3 bg-surface-raised rounded w-1/2" />
              <div className="h-3 bg-surface-raised rounded w-3/4" />
            </div>
          </div>
        )}

        {/* Collapsible Content */}
        {!isLoading && hasLoaded && data && isExpanded && (
          <div className="space-y-3 pt-2 border-t border-border/50 text-xs leading-relaxed animate-in fade-in-50 duration-200">
            {/* 2-3 sentence synthesis */}
            <p className="text-foreground/90 font-sans leading-normal">
              {data.summary}
            </p>

            {/* Key Points */}
            {data.key_points && data.key_points.length > 0 && (
              <div className="space-y-1.5">
                <span className="font-mono text-[10px] font-bold uppercase tracking-wider text-muted-foreground">
                  Key Takeaways:
                </span>
                <ul className="space-y-1 pl-4 list-disc marker:text-accent text-muted-foreground">
                  {data.key_points.map((pt, idx) => (
                    <li key={idx} className="text-foreground/80">
                      {pt}
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {/* Disagreement / Debate if present */}
            {data.disagreement && (
              <div className="p-2.5 rounded-lg bg-surface-raised/60 border border-border/70 space-y-1">
                <span className="font-mono text-[10px] font-bold uppercase tracking-wider text-accent flex items-center gap-1">
                  <AlertCircle className="h-3 w-3" />
                  Primary Point of Debate:
                </span>
                <p className="text-foreground/80 text-[11px] leading-relaxed">
                  {data.disagreement}
                </p>
              </div>
            )}
          </div>
        )}
      </CardContent>
    </Card>
  );
}
